def safe_prepare_output(output_root: Path, *, overwrite: bool) -> Path:
    resolved = output_root.resolve()
    forbidden = {
        REPO_ROOT.resolve(),
        DATASETS_ROOT.resolve(),
        PROVENANCE_ROOT.resolve(),
        RESULTS_ROOT.resolve(),
    }
    if resolved in forbidden:
        raise ValueError(f"Refusing broad output directory: {resolved}")
    if resolved.exists():
        if not overwrite:
            raise FileExistsError(f"Output exists: {resolved}; pass --overwrite for this exact directory.")
        shutil.rmtree(resolved)
    resolved.mkdir(parents=True, exist_ok=False)
    return resolved


def read_screen_rows(path: Path) -> tuple[list[dict[str, str]], list[str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        rows = list(reader)
        fields = list(reader.fieldnames or [])
    if not rows:
        raise ValueError(f"Screening CSV contains no rows: {path}")
    required = {"sample_id", "filename", "language", "dataset_name", "pool", "candidate"}
    missing = sorted(required - set(fields))
    if missing:
        raise ValueError(f"Screening CSV is missing required columns: {missing}")
    model_names = sorted(
        field[: -len("_is_tool_call_top1")]
        for field in fields
        if field.endswith("_is_tool_call_top1")
    )
    if not model_names:
        raise ValueError("Could not find *_is_tool_call_top1 model columns in screening CSV")
    return rows, model_names


def build_screen_index(rows: Sequence[dict[str, str]]) -> dict[tuple[str, str, str], dict[str, str]]:
    index: dict[tuple[str, str, str], dict[str, str]] = {}
    for row in rows:
        pool = normalize_word(row["pool"])
        candidate = normalize_word(row["candidate"])
        filename = str(row["filename"])
        key = (pool, candidate, filename)
        if key in index:
            raise ValueError(f"Duplicate screening row: {key}")
        index[key] = row
    return index


def screen_row_is_valid(row: dict[str, str], *, pool: str, model_names: Sequence[str]) -> bool:
    expected = pool == "clean"
    for model_name in model_names:
        key = f"{model_name}_is_tool_call_top1"
        if key not in row or parse_bool(row[key]) != expected:
            return False
    return True


def read_base_records(source_root: Path, screen_index: dict[tuple[str, str, str], dict[str, str]]) -> list[SourceRecord]:
    clean_root = source_root / "clean"
    if not clean_root.is_dir():
        raise FileNotFoundError(f"Missing base clean prompt directory: {clean_root}")
    records: list[SourceRecord] = []
    for path in sorted(clean_root.glob("*.txt")):
        metadata = next(
            (
                row
                for (pool, _candidate, filename), row in screen_index.items()
                if pool == "clean" and filename == path.name
            ),
            None,
        )
        if metadata is None:
            # A fresh screen may intentionally cover only a subset of the base pool.
            continue
        records.append(
            SourceRecord(
                filename=path.name,
                sample_id=str(metadata["sample_id"]),
                language=str(metadata.get("language") or "unknown"),
                dataset_name=str(metadata.get("dataset_name") or "unknown"),
                scaffold=path.read_text(encoding="utf-8"),
            )
        )
    if not records:
        raise ValueError("No base prompts overlap the screening CSV")
    return records


def load_tokenizers(paths: Sequence[Path]) -> list[tuple[str, object]]:
    loaded: list[tuple[str, object]] = []
    seen: set[str] = set()
    for raw_path in paths:
        path = raw_path.expanduser().resolve()
        key = str(path)
        if key in seen:
            continue
        seen.add(key)
        tokenizer = AutoTokenizer.from_pretrained(path, trust_remote_code=True)
        loaded.append((path.name, tokenizer))
    if not loaded:
        raise ValueError("At least one tokenizer is required for token-length alignment")
    return loaded


def prompt_lengths(prompt: str, tokenizers: Sequence[tuple[str, object]]) -> dict[str, int]:
    return {
        label: len(tokenizer(prompt, add_special_tokens=False)["input_ids"])
        for label, tokenizer in tokenizers
    }


def feasible_pairs_for_record(
    record: SourceRecord,
    *,
    screen_index: dict[tuple[str, str, str], dict[str, str]],
    model_names: Sequence[str],
    tokenizers: Sequence[tuple[str, object]],
) -> tuple[list[tuple[str, str]], dict[tuple[str, str], tuple[str, str, str, str, dict[str, int]]]]:
    clean_options: dict[str, tuple[str, str, dict[str, int]]] = {}
    corrupt_options: dict[str, tuple[str, str, dict[str, int]]] = {}
    for pool, candidates, target in (
        ("clean", CLEAN_CANDIDATES, clean_options),
        ("corrupt", CORRUPT_CANDIDATES, corrupt_options),
    ):
        for candidate in candidates:
            row = screen_index.get((pool, candidate, record.filename))
            if row is None or not screen_row_is_valid(row, pool=pool, model_names=model_names):
                continue
            prompt, line = replace_instruction_verb(record.scaffold, candidate)
            target[candidate] = (prompt, line, prompt_lengths(prompt, tokenizers))

    feasible: list[tuple[str, str]] = []
    rendered: dict[tuple[str, str], tuple[str, str, str, str, dict[str, int]]] = {}
    for clean_candidate, (clean_prompt, clean_line, clean_lengths) in clean_options.items():
        for corrupt_candidate, (corrupt_prompt, corrupt_line, corrupt_lengths) in corrupt_options.items():
            if all(clean_lengths[label] == corrupt_lengths[label] for label in clean_lengths):
                pair = (clean_candidate, corrupt_candidate)
                feasible.append(pair)
                rendered[pair] = (
                    clean_prompt,
                    corrupt_prompt,
                    clean_line,
                    corrupt_line,
                    dict(clean_lengths),
                )
    return sorted(feasible), rendered


def allocate_language_quotas(
    records_by_language: dict[str, list[SourceRecord]],
    *,
    target_pairs: int,
    requested: dict[str, int],
) -> dict[str, int]:
    available = {language: len(rows) for language, rows in records_by_language.items()}
    total_available = sum(available.values())
    if target_pairs <= 0:
        return available
    if target_pairs > total_available:
        raise ValueError(f"Requested {target_pairs} pairs but only {total_available} are eligible")
    if requested:
        unknown = sorted(set(requested) - set(available))
        if unknown:
            raise ValueError(f"Language quota(s) do not occur among eligible rows: {unknown}")
        if sum(requested.values()) != target_pairs:
            raise ValueError("The sum of --language-quotas must equal --target-pairs")
        too_large = {language: count for language, count in requested.items() if count > available[language]}
        if too_large:
            raise ValueError(f"Requested more pairs than available for language(s): {too_large}")
        return {language: int(requested.get(language, 0)) for language in sorted(available)}

    ideal = {language: available[language] * target_pairs / total_available for language in available}
    quotas = {language: min(available[language], int(math.floor(ideal[language]))) for language in available}
    remaining = target_pairs - sum(quotas.values())
    for language in sorted(available, key=lambda item: (-(ideal[item] - quotas[item]), item)):
        if remaining <= 0:
            break
        if quotas[language] < available[language]:
            quotas[language] += 1
            remaining -= 1
    if remaining:
        raise RuntimeError("Could not allocate all requested fresh-dataset slots")
    return quotas


def choose_membership(
    records: Sequence[SourceRecord],
    *,
    target_pairs: int,
    language_quotas: dict[str, int],
    seed: int,
) -> tuple[list[SourceRecord], list[SourceRecord], dict[str, int]]:
    by_language: dict[str, list[SourceRecord]] = defaultdict(list)
    for record in records:
        by_language[record.language].append(record)
    quotas = allocate_language_quotas(by_language, target_pairs=target_pairs, requested=language_quotas)
    selected: list[SourceRecord] = []
    excluded: list[SourceRecord] = []
    for language in sorted(by_language):
        ranked = sorted(by_language[language], key=lambda record: (stable_rank(seed, record.filename), record.filename))
        selected.extend(ranked[: quotas[language]])
        excluded.extend(ranked[quotas[language] :])
    return sorted(selected, key=lambda record: record.filename), sorted(excluded, key=lambda record: record.filename), quotas


def choose_assignments(
    records: Sequence[SourceRecord],
    *,
    feasible_by_filename: dict[str, list[tuple[str, str]]],
    rendered_by_filename: dict[tuple[str, tuple[str, str]], tuple[str, str, str, str, dict[str, int]]],
    screen_index: dict[tuple[str, str, str], dict[str, str]],
) -> list[Assignment]:
    pair_counts: Counter[tuple[str, str]] = Counter()
    clean_counts: Counter[str] = Counter()
    corrupt_counts: Counter[str] = Counter()
    assignments: list[Assignment] = []
    # Least flexible prompts are assigned first, reproducing the documented
    # maximum-aligned balancing policy while making the fresh membership explicit.
    ordered = sorted(records, key=lambda record: (len(feasible_by_filename[record.filename]), record.filename))
    for record in ordered:
        feasible = feasible_by_filename[record.filename]
        if not feasible:
            raise ValueError(f"Internal error: selected record has no feasible candidate pair: {record.filename}")
        selected_pair = min(
            feasible,
            key=lambda pair: (
                pair_counts[pair],
                corrupt_counts[pair[1]],
                clean_counts[pair[0]],
                pair[1],
                pair[0],
            ),
        )
        clean_candidate, corrupt_candidate = selected_pair
        pair_counts[selected_pair] += 1
        clean_counts[clean_candidate] += 1
        corrupt_counts[corrupt_candidate] += 1
        clean_prompt, corrupt_prompt, clean_line, corrupt_line, token_lengths = rendered_by_filename[
            (record.filename, selected_pair)
        ]
        assignments.append(
            Assignment(
                record=record,
                clean_candidate=clean_candidate,
                corrupt_candidate=corrupt_candidate,
                feasible_pairs=tuple(feasible),
                clean_prompt=clean_prompt,
                corrupt_prompt=corrupt_prompt,
                clean_line=clean_line,
                corrupt_line=corrupt_line,
                token_lengths=token_lengths,
                clean_screen_row=screen_index[("clean", clean_candidate, record.filename)],
                corrupt_screen_row=screen_index[("corrupt", corrupt_candidate, record.filename)],
            )
        )
    return sorted(assignments, key=lambda assignment: assignment.record.filename)


def pair_stability_score(
    record: SourceRecord,
    pair: tuple[str, str],
    *,
    screen_index: dict[tuple[str, str, str], dict[str, str]],
    model_names: Sequence[str],
) -> float:
    """Conservative confidence score used only to break exact-grid ties.

    Membership remains a hard top-1 behavior condition.  Among several
    behavior-valid assignments, prefer the one with the largest minimum
    clean-call / corrupt-no-call probability across the required models.
    """

    clean_candidate, corrupt_candidate = pair
    clean_row = screen_index[("clean", clean_candidate, record.filename)]
    corrupt_row = screen_index[("corrupt", corrupt_candidate, record.filename)]
    values: list[float] = []
    for model_name in model_names:
        try:
            clean_prob = float(clean_row[f"{model_name}_tool_call_prob"])
            corrupt_prob = float(corrupt_row[f"{model_name}_tool_call_prob"])
        except (KeyError, TypeError, ValueError):
            # Older screening files can lack probabilities.  They still have
            # the hard validity columns, so retain deterministic selection.
            continue
        values.extend((clean_prob, 1.0 - corrupt_prob))
    return min(values) if values else 0.0


def choose_exact_grid_assignments(
    records: Sequence[SourceRecord],
    *,
    feasible_by_filename: dict[str, list[tuple[str, str]]],
    rendered_by_filename: dict[tuple[str, tuple[str, str]], tuple[str, str, str, str, dict[str, int]]],
    screen_index: dict[tuple[str, str, str], dict[str, str]],
    model_names: Sequence[str],
    target_pairs: int,
    language_quotas: dict[str, int],
    seed: int,
) -> list[Assignment]:
    """Jointly select sources and assignments with an exact verb-pair grid.

    The old fresh-data builder first sampled source records and then assigned
    verbs greedily.  That can starve a rare-but-valid clean verb before the
    assignment stage sees it.  This formulation solves the actual selection
    problem in one pass: a source is used at most once, language membership is
    fixed, and every clean×corrupt cell receives the same number of rows.
    """

    try:
        import numpy as np
        from scipy.optimize import Bounds, LinearConstraint, milp
        from scipy.sparse import lil_matrix
    except ImportError as exc:  # pragma: no cover - scipy is a project dependency.
        raise RuntimeError("exact_grid selection requires scipy") from exc

    combinations = [(clean, corrupt) for clean in CLEAN_CANDIDATES for corrupt in CORRUPT_CANDIDATES]
    if target_pairs <= 0 or target_pairs % len(combinations) != 0:
        raise ValueError(
            f"exact_grid requires a positive target divisible by {len(combinations)}; got {target_pairs}"
        )
    if sum(language_quotas.values()) != target_pairs:
        raise ValueError("Exact-grid language quotas must sum to --target-pairs")
    per_cell = target_pairs // len(combinations)

    # One binary variable for every behavior-valid and token-aligned
    # source/verb-pair edge.  The graph is sparse: the corresponding source
    # may expose several viable cells, but can only be selected once.
    variables: list[tuple[SourceRecord, tuple[str, str]]] = []
    source_columns: dict[str, list[int]] = defaultdict(list)
    combo_columns: dict[tuple[str, str], list[int]] = defaultdict(list)
    language_columns: dict[str, list[int]] = defaultdict(list)
    costs: list[float] = []
    for record in records:
        for pair in feasible_by_filename[record.filename]:
            column = len(variables)
            variables.append((record, pair))
            source_columns[record.filename].append(column)
            combo_columns[pair].append(column)
            language_columns[record.language].append(column)
            # Larger confidence is better.  The tiny deterministic rank term
            # makes equal-confidence solutions replayable without affecting
            # the behavioral membership criterion.
            rank = int(stable_rank(seed, f"{record.filename}:{pair[0]}:{pair[1]}")[:16], 16) / 2**64
            costs.append(-pair_stability_score(record, pair, screen_index=screen_index, model_names=model_names) + 1e-8 * rank)
    if not variables:
        raise ValueError("No feasible source/verb edges available for exact-grid selection")

    constraint_count = len(source_columns) + len(combinations) + len(language_quotas)
    matrix = lil_matrix((constraint_count, len(variables)), dtype=float)
    lower: list[float] = []
    upper: list[float] = []
    row_index = 0
    for filename in sorted(source_columns):
        for column in source_columns[filename]:
            matrix[row_index, column] = 1.0
        lower.append(0.0)
        upper.append(1.0)
        row_index += 1
    for pair in combinations:
        for column in combo_columns[pair]:
            matrix[row_index, column] = 1.0
        lower.append(float(per_cell))
        upper.append(float(per_cell))
        row_index += 1
    for language in sorted(language_quotas):
        for column in language_columns[language]:
            matrix[row_index, column] = 1.0
        quota = float(language_quotas[language])
        lower.append(quota)
        upper.append(quota)
        row_index += 1

    result = milp(
        c=np.asarray(costs, dtype=float),
        integrality=np.ones(len(variables), dtype=int),
        bounds=Bounds(0.0, 1.0),
        constraints=LinearConstraint(matrix.tocsr(), np.asarray(lower), np.asarray(upper)),
    )
    if result.status != 0 or result.x is None:
        raise RuntimeError(f"Could not find an exact balanced verb grid: {result.message}")

    assignments: list[Assignment] = []
    for column, value in enumerate(result.x):
        if value <= 0.5:
            continue
        record, pair = variables[column]
        clean_candidate, corrupt_candidate = pair
        clean_prompt, corrupt_prompt, clean_line, corrupt_line, token_lengths = rendered_by_filename[
            (record.filename, pair)
        ]
        assignments.append(
            Assignment(
                record=record,
                clean_candidate=clean_candidate,
                corrupt_candidate=corrupt_candidate,
                feasible_pairs=tuple(feasible_by_filename[record.filename]),
                clean_prompt=clean_prompt,
                corrupt_prompt=corrupt_prompt,
                clean_line=clean_line,
                corrupt_line=corrupt_line,
                token_lengths=token_lengths,
                clean_screen_row=screen_index[("clean", clean_candidate, record.filename)],
                corrupt_screen_row=screen_index[("corrupt", corrupt_candidate, record.filename)],
            )
        )
    if len(assignments) != target_pairs:
        raise AssertionError(f"Exact-grid solver returned {len(assignments)} assignments, expected {target_pairs}")
    if Counter((item.clean_candidate, item.corrupt_candidate) for item in assignments) != Counter(
        {pair: per_cell for pair in combinations}
    ):
        raise AssertionError("Exact-grid solver did not meet every verb-pair quota")
    if Counter(item.record.language for item in assignments) != Counter(language_quotas):
        raise AssertionError("Exact-grid solver did not meet language quotas")
    if len({item.record.filename for item in assignments}) != len(assignments):
        raise AssertionError("Exact-grid solver reused a source record")
    return sorted(assignments, key=lambda assignment: assignment.record.filename)


def allocate_test_counts(assignments: Sequence[Assignment], fraction: float) -> dict[str, int]:
    by_language: Counter[str] = Counter(assignment.record.language for assignment in assignments)
    target_total = int(round(len(assignments) * fraction))
    ideal = {language: count * fraction for language, count in by_language.items()}
    counts = {language: int(math.floor(value)) for language, value in ideal.items()}
    remaining = target_total - sum(counts.values())
    for language in sorted(by_language, key=lambda item: (-(ideal[item] - counts[item]), item)):
        if remaining <= 0:
            break
        if counts[language] < by_language[language]:
            counts[language] += 1
            remaining -= 1
    return counts


def choose_splits(assignments: Sequence[Assignment], *, test_fraction: float, seed: int) -> tuple[dict[str, str], dict[str, int]]:
    if not 0.0 < test_fraction < 1.0:
        raise ValueError("--test-fraction must be strictly between 0 and 1")
    test_counts = allocate_test_counts(assignments, test_fraction)
    by_language: dict[str, list[Assignment]] = defaultdict(list)
    for assignment in assignments:
        by_language[assignment.record.language].append(assignment)
    split_by_filename: dict[str, str] = {}
    for language, group in by_language.items():
        ranked = sorted(group, key=lambda assignment: (stable_rank(seed + 1, assignment.record.filename), assignment.record.filename))
        for assignment in ranked[: test_counts[language]]:
            split_by_filename[assignment.record.filename] = "test"
        for assignment in ranked[test_counts[language] :]:
            split_by_filename[assignment.record.filename] = "train"
    return split_by_filename, test_counts


def choose_exact_grid_splits(
    assignments: Sequence[Assignment], *, test_fraction: float, seed: int
) -> tuple[dict[str, str], dict[str, int]]:
    """Split an exact full grid while retaining every cell's proportion.

    For the 500-pair, 5×5 configuration this gives four test and sixteen
    train rows per clean×corrupt cell, while retaining the language-stratified
    400/100 convention.
    """

    try:
        import numpy as np
        from scipy.optimize import Bounds, LinearConstraint, milp
        from scipy.sparse import lil_matrix
    except ImportError as exc:  # pragma: no cover - scipy is a project dependency.
        raise RuntimeError("exact_grid split selection requires scipy") from exc

    if not 0.0 < test_fraction < 1.0:
        raise ValueError("--test-fraction must be strictly between 0 and 1")
    combinations = [(clean, corrupt) for clean in CLEAN_CANDIDATES for corrupt in CORRUPT_CANDIDATES]
    target_total = int(round(len(assignments) * test_fraction))
    if target_total % len(combinations) != 0:
        raise ValueError(
            f"Exact-grid test split needs {target_total} to be divisible by {len(combinations)} cells"
        )
    per_cell = target_total // len(combinations)
    test_counts = allocate_test_counts(assignments, test_fraction)
    combo_columns: dict[tuple[str, str], list[int]] = defaultdict(list)
    language_columns: dict[str, list[int]] = defaultdict(list)
    for index, assignment in enumerate(assignments):
        combo_columns[(assignment.clean_candidate, assignment.corrupt_candidate)].append(index)
        language_columns[assignment.record.language].append(index)
    expected_full = len(assignments) // len(combinations)
    if len(assignments) % len(combinations) != 0 or any(
        len(combo_columns[pair]) != expected_full for pair in combinations
    ):
        raise ValueError("Exact-grid split requires an already balanced full verb grid")

    matrix = lil_matrix((len(combinations) + len(test_counts), len(assignments)), dtype=float)
    lower: list[float] = []
    upper: list[float] = []
    row_index = 0
    for pair in combinations:
        for column in combo_columns[pair]:
            matrix[row_index, column] = 1.0
        lower.append(float(per_cell))
        upper.append(float(per_cell))
        row_index += 1
    for language in sorted(test_counts):
        for column in language_columns[language]:
            matrix[row_index, column] = 1.0
        quota = float(test_counts[language])
        lower.append(quota)
        upper.append(quota)
        row_index += 1
    costs = np.asarray(
        [int(stable_rank(seed + 1, assignment.record.filename)[:16], 16) / 2**64 for assignment in assignments],
        dtype=float,
    )
    result = milp(
        c=costs,
        integrality=np.ones(len(assignments), dtype=int),
        bounds=Bounds(0.0, 1.0),
        constraints=LinearConstraint(matrix.tocsr(), np.asarray(lower), np.asarray(upper)),
    )
    if result.status != 0 or result.x is None:
        raise RuntimeError(f"Could not construct an exact-grid train/test split: {result.message}")
    split_by_filename = {
        assignment.record.filename: "test" if result.x[index] > 0.5 else "train"
        for index, assignment in enumerate(assignments)
    }
    if Counter(split_by_filename.values()) != Counter({"train": len(assignments) - target_total, "test": target_total}):
        raise AssertionError("Exact-grid split has an unexpected train/test size")
    return split_by_filename, test_counts


def write_jsonl(path: Path, rows: Iterable[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def write_csv(path: Path, rows: Sequence[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields: list[str] = []
    seen: set[str] = set()
    for row in rows:
        for field in row:
            if field not in seen:
                seen.add(field)
                fields.append(field)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def flattened_screen_metrics(assignment: Assignment, model_names: Sequence[str]) -> dict[str, object]:
    output: dict[str, object] = {}
    for model_name in model_names:
        for side, row in (("clean", assignment.clean_screen_row), ("corrupt", assignment.corrupt_screen_row)):
            for field in ("is_tool_call_top1", "tool_call_prob", "top1_token_id", "top1_token_text", "top1_prob"):
                key = f"{model_name}_{field}"
                if key in row:
                    output[f"{model_name}_{side}_{field}"] = row[key]
    return output


def manifest_row(
    assignment: Assignment,
    *,
    split: str,
    model_names: Sequence[str],
    content_audit_row: dict[str, object] | None = None,
    dataset_version: str = "fresh_screened",
) -> dict[str, object]:
    row: dict[str, object] = {
        "dataset_version": dataset_version,
        "split": split,
        "sample_id": assignment.record.sample_id,
        "source_filename": assignment.record.filename,
        "output_filename": assignment.record.filename,
        "language": assignment.record.language,
        "dataset_name": assignment.record.dataset_name,
        "source_scaffold_sha256": hashlib.sha256(assignment.record.scaffold.encode("utf-8")).hexdigest(),
        "clean_candidate": assignment.clean_candidate,
        "corrupt_candidate": assignment.corrupt_candidate,
        "clean_rendered_first_user_line": assignment.clean_line,
        "corrupt_rendered_first_user_line": assignment.corrupt_line,
        "clean_prompt_sha256": hashlib.sha256(assignment.clean_prompt.encode("utf-8")).hexdigest(),
        "corrupt_prompt_sha256": hashlib.sha256(assignment.corrupt_prompt.encode("utf-8")).hexdigest(),
        "token_lengths": assignment.token_lengths,
        "token_length_aligned": True,
        "selection_model_metrics": {
            model_name: {
                "clean": {
                    key[len(model_name) + 1 :]: value
                    for key, value in assignment.clean_screen_row.items()
                    if key.startswith(f"{model_name}_")
                },
                "corrupt": {
                    key[len(model_name) + 1 :]: value
                    for key, value in assignment.corrupt_screen_row.items()
                    if key.startswith(f"{model_name}_")
                },
            }
            for model_name in model_names
        },
    }
    if content_audit_row is not None:
        row["content_audit"] = {
            "profile": "code_strict",
            "passed": bool(content_audit_row["content_audit_passed"]),
            "reasons": content_audit_row["content_audit_reasons"],
            "body_word_count": content_audit_row["body_word_count"],
        }
    return row


def main() -> None:
    args = parse_args()
    if args.target_pairs < 0:
        raise ValueError("--target-pairs must be non-negative")
    screen_rows, model_names = read_screen_rows(args.screened_csv.resolve())
    screen_index = build_screen_index(screen_rows)
    source_root = args.source_root.resolve()
    source_records = read_base_records(source_root, screen_index)
    content_audit_rows: list[dict[str, object]] = []
    content_audit_by_filename: dict[str, dict[str, object]] = {}
    content_rejected_rows: list[dict[str, object]] = []
    if args.content_audit_profile == "code_strict":
        records = []
        for record in source_records:
            audit = audit_code_scaffold(record.scaffold)
            audit_row = audit.as_dict(
                filename=record.filename,
                sample_id=record.sample_id,
                dataset_name=record.dataset_name,
            )
            content_audit_rows.append(audit_row)
            content_audit_by_filename[record.filename] = audit_row
            if audit.passed:
                records.append(record)
            else:
                content_rejected_rows.append(
                    {
                        **audit_row,
                        "reason": "content_audit_rejection",
                    }
                )
    else:
        records = list(source_records)
    if args.tokenizer:
        tokenizer_paths = args.tokenizer
    else:
        tokenizer_paths = [
            MODEL_PATHS["qwen3_1p7b"],
            MODEL_PATHS["qwen3_4b"],
            MODEL_PATHS["qwen3_8b"],
        ]
        # A four-model screening CSV must also be aligned under the 14B
        # tokenizer by default; otherwise a caller could accidentally satisfy
        # the behavior intersection while checking token parity under only
        # the historical three tokenizers.
        if "Qwen3-14B" in model_names:
            tokenizer_paths.append(MODEL_PATHS["qwen3_14b"])
    tokenizers = load_tokenizers(tokenizer_paths)
    if "Qwen3-14B" in model_names and len(tokenizers) < 4:
        raise ValueError(
            "The screening CSV contains Qwen3-14B; provide a distinct Qwen3-14B tokenizer "
            "so four-scale token alignment is checked."
        )

    eligible: list[SourceRecord] = []
    infeasible_rows: list[dict[str, object]] = []
    feasible_by_filename: dict[str, list[tuple[str, str]]] = {}
    rendered_by_filename: dict[tuple[str, tuple[str, str]], tuple[str, str, str, str, dict[str, int]]] = {}
    for record in records:
        feasible, rendered = feasible_pairs_for_record(
            record,
            screen_index=screen_index,
            model_names=model_names,
            tokenizers=tokenizers,
        )
        if feasible:
            eligible.append(record)
            feasible_by_filename[record.filename] = feasible
            for pair, payload in rendered.items():
                rendered_by_filename[(record.filename, pair)] = payload
        else:
            infeasible_rows.append(
                {
                    "filename": record.filename,
                    "sample_id": record.sample_id,
                    "language": record.language,
                    "dataset_name": record.dataset_name,
                    "reason": "no_behavior_valid_token_aligned_candidate_pair",
                }
            )

    requested_quotas = parse_quotas(args.language_quotas)
    if requested_quotas and args.target_pairs <= 0:
        raise ValueError("--language-quotas requires a positive --target-pairs")
    if args.assignment_policy == "exact_grid":
        if args.target_pairs <= 0:
            raise ValueError("--assignment-policy exact_grid requires a positive --target-pairs")
        by_language: dict[str, list[SourceRecord]] = defaultdict(list)
        for record in eligible:
            by_language[record.language].append(record)
        language_quotas = allocate_language_quotas(
            by_language,
            target_pairs=args.target_pairs,
            requested=requested_quotas,
        )
        assignments = choose_exact_grid_assignments(
            eligible,
            feasible_by_filename=feasible_by_filename,
            rendered_by_filename=rendered_by_filename,
            screen_index=screen_index,
            model_names=model_names,
            target_pairs=args.target_pairs,
            language_quotas=language_quotas,
            seed=args.seed,
        )
        selected_filenames = {assignment.record.filename for assignment in assignments}
        selected_records = [record for record in eligible if record.filename in selected_filenames]
        quota_excluded = [record for record in eligible if record.filename not in selected_filenames]
    else:
        selected_records, quota_excluded, language_quotas = choose_membership(
            eligible,
            target_pairs=args.target_pairs,
            language_quotas=requested_quotas,
            seed=args.seed,
        )
        assignments = choose_assignments(
            selected_records,
            feasible_by_filename=feasible_by_filename,
            rendered_by_filename=rendered_by_filename,
            screen_index=screen_index,
        )
    if args.assignment_policy == "exact_grid":
        split_by_filename, test_counts = choose_exact_grid_splits(
            assignments,
            test_fraction=args.test_fraction,
            seed=args.seed,
        )
        split_policy = "exact_clean_x_corrupt_grid_with_language_stratification"
    else:
        split_by_filename, test_counts = choose_splits(assignments, test_fraction=args.test_fraction, seed=args.seed)
        split_policy = "language_stratified_hash_split"
    output_root = safe_prepare_output(args.output_root, overwrite=args.overwrite)
    dataset_version = (
        "v4_code_500_balanced"
        if args.assignment_policy == "exact_grid" and args.content_audit_profile == "code_strict" and args.target_pairs == 500
        else (
            "v3_code_500"
            if args.content_audit_profile == "code_strict" and args.target_pairs == 500
            else "fresh_screened"
        )
    )

    manifest_rows: dict[tuple[str, str], list[dict[str, object]]] = defaultdict(list)
    selection_rows: list[dict[str, object]] = []
    split_rows: list[dict[str, object]] = []
    for assignment in assignments:
        split = split_by_filename[assignment.record.filename]
        clean_path = output_root / split / "clean" / assignment.record.filename
        corrupt_path = output_root / split / "corrupt" / assignment.record.filename
        clean_path.parent.mkdir(parents=True, exist_ok=True)
        corrupt_path.parent.mkdir(parents=True, exist_ok=True)
        clean_path.write_text(assignment.clean_prompt, encoding="utf-8")
        corrupt_path.write_text(assignment.corrupt_prompt, encoding="utf-8")
        row = manifest_row(
            assignment,
            split=split,
            model_names=model_names,
            content_audit_row=content_audit_by_filename.get(assignment.record.filename),
            dataset_version=dataset_version,
        )
        manifest_rows[(split, "clean")].append(row)
        manifest_rows[(split, "corrupt")].append(row)
        selection_rows.append(
            {
                "sample_id": assignment.record.sample_id,
                "filename": assignment.record.filename,
                "language": assignment.record.language,
                "dataset_name": assignment.record.dataset_name,
                "clean_candidate": assignment.clean_candidate,
                "corrupt_candidate": assignment.corrupt_candidate,
                "content_audit_profile": args.content_audit_profile,
                "content_audit_passed": (
                    content_audit_by_filename.get(assignment.record.filename, {}).get("content_audit_passed", True)
                ),
                "content_audit_reasons": content_audit_by_filename.get(
                    assignment.record.filename, {}
                ).get("content_audit_reasons", ""),
                "n_feasible_pairs": len(assignment.feasible_pairs),
                "feasible_pairs": "|".join(f"{clean}->{corrupt}" for clean, corrupt in assignment.feasible_pairs),
                "token_lengths": json.dumps(assignment.token_lengths, sort_keys=True),
                **flattened_screen_metrics(assignment, model_names),
            }
        )
        split_rows.append(
            {
                "sample_id": assignment.record.sample_id,
                "filename": assignment.record.filename,
                "language": assignment.record.language,
                "dataset_name": assignment.record.dataset_name,
                "split": split,
            }
        )
    for split in ("train", "test"):
        for side in ("clean", "corrupt"):
            write_jsonl(output_root / split / side / "manifest.jsonl", manifest_rows[(split, side)])

    write_csv(output_root / "selection_manifest.csv", selection_rows)
    write_csv(output_root / "split_manifest.csv", split_rows)
    write_csv(output_root / "ineligible_base_pairs.csv", infeasible_rows)
    write_csv(
        output_root / "eligible_but_not_selected.csv",
        [
            {
                "sample_id": record.sample_id,
                "filename": record.filename,
                "language": record.language,
                "dataset_name": record.dataset_name,
                "reason": "target_pairs_or_language_quota",
            }
            for record in quota_excluded
        ],
    )
    # Keep the full deterministic audit, including rejected rows, alongside
    # the selected prompts.  This makes the extra 1,711 -> 500 membership step
    # inspectable without rerunning a model.
    write_csv(output_root / "content_audit.csv", content_audit_rows)
    write_csv(output_root / "content_rejected.csv", content_rejected_rows)
    shutil.copy2(args.screened_csv.resolve(), output_root / "candidate_screening.csv")

    language_counts = Counter(assignment.record.language for assignment in assignments)
    clean_counts = Counter(assignment.clean_candidate for assignment in assignments)
    corrupt_counts = Counter(assignment.corrupt_candidate for assignment in assignments)
    split_counts = Counter(row["split"] for row in split_rows)
    source_fingerprint = {
        "screened_csv_sha256": sha256_file(args.screened_csv.resolve()),
        "base_clean_file_count": len(list((source_root / "clean").glob("*.txt"))),
    }
    summary = {
        "dataset_version": dataset_version,
        "warning": "This is a new deterministic dataset definition, not an exact reproduction of frozen v2_1500. Use rebuild_dataset_v2 for that.",
        "source_root": str(source_root),
        "screened_csv": str(args.screened_csv.resolve()),
        "screening_models": model_names,
        "content_audit_profile": args.content_audit_profile,
        "n_source_records_before_content_audit": len(source_records),
        "n_content_audit_pass": len(records) if args.content_audit_profile == "code_strict" else None,
        "n_content_audit_rejected": len(content_rejected_rows),
        "tokenizers": [str(path.expanduser().resolve()) for path in tokenizer_paths],
        "target_pairs": int(args.target_pairs),
        "assignment_policy": args.assignment_policy,
        "split_policy": split_policy,
        "language_quotas": language_quotas,
        "test_fraction": float(args.test_fraction),
        "seed": int(args.seed),
        "n_screened_base_pairs": len(source_records),
        "n_eligible_pairs": len(eligible),
        "n_ineligible_pairs": len(infeasible_rows),
        "n_selected_pairs": len(assignments),
        "split_counts": dict(sorted(split_counts.items())),
        "test_language_counts": test_counts,
        "language_counts": dict(sorted(language_counts.items())),
        "clean_candidate_counts": dict(sorted(clean_counts.items())),
        "corrupt_candidate_counts": dict(sorted(corrupt_counts.items())),
        "verb_pair_counts": {
            f"{clean}->{corrupt}": sum(
                1
                for assignment in assignments
                if assignment.clean_candidate == clean and assignment.corrupt_candidate == corrupt
            )
            for clean in CLEAN_CANDIDATES
            for corrupt in CORRUPT_CANDIDATES
        },
        "source_fingerprint": source_fingerprint,
    }
    write_json(output_root / "construction_summary.json", summary)
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
