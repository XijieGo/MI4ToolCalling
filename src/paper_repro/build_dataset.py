#!/usr/bin/env python3
"""Build a new, versioned aligned tool-call dataset from fresh screening output.

This is intentionally different from ``rebuild_dataset_v2``.  The latter is an
exact replay of the frozen submitted 1,500-pair definition.  This module is
for a new run of the behavioral screen: it validates each candidate across the
specified model columns, enforces token-length alignment, chooses balanced
clean/corrupt verbs deterministically, and creates a new train/test dataset
without mutating ``datasets/``.

The original project contained a similarly named builder that reconstructed a
prompt from a longest common suffix.  That operation could corrupt a line such
as ``Save the ...`` into ``Save e the ...``.  All rendering here goes through
``replace_instruction_verb``, which changes only the first instruction word.
"""
