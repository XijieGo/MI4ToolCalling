CLEAN_CANDIDATES = ("complete", "build", "write", "save", "add")
CORRUPT_CANDIDATES = ("discuss", "explore", "inspect", "review", "study")


@dataclass(frozen=True)
class SourceRecord:
    filename: str
    sample_id: str
    language: str
    dataset_name: str
    scaffold: str


@dataclass(frozen=True)
class Assignment:
    record: SourceRecord
    clean_candidate: str
    corrupt_candidate: str
    feasible_pairs: tuple[tuple[str, str], ...]
    clean_prompt: str
    corrupt_prompt: str
    clean_line: str
    corrupt_line: str
    token_lengths: dict[str, int]
    clean_screen_row: dict[str, str]
    corrupt_screen_row: dict[str, str]


def parse_bool(value: object) -> bool:
    return str(value).strip().lower() in {"1", "true", "yes"}


def normalize_word(value: str) -> str:
    return str(value).strip().lower()


def stable_rank(seed: int, filename: str) -> str:
    return hashlib.sha256(f"{seed}:{filename}".encode("utf-8")).hexdigest()


def parse_quotas(raw: str) -> dict[str, int]:
    if not raw.strip():
        return {}
    quotas: dict[str, int] = {}
    for item in raw.split(","):
        if "=" not in item:
            raise ValueError("Language quotas must use LANGUAGE=COUNT, e.g. cpp=506,java=507,python=487")
        language, count_text = item.split("=", 1)
        language = language.strip()
        count = int(count_text)
        if not language or count < 0:
            raise ValueError(f"Invalid language quota: {item!r}")
        if language in quotas:
            raise ValueError(f"Duplicate language quota: {language}")
        quotas[language] = count
    return quotas


